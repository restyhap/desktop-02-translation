/**
 * 极简 i18n —— 界面语言层（UI locale）
 *
 * 设计要点：
 * - 与「翻译内容语言」（SUPPORTED_LANGUAGES，含 ja）完全解耦：这里只管界面文案；
 * - 支持 9 种 UI 语言：zh（默认）/ en / de / fr / es / it / pt / ru / ko。
 *   刻意不含 ja —— 用户明确屏蔽日本市场，禁止加入日语；
 * - LocaleProvider 持有当前语言，写入 localStorage("ui-locale")；
 * - 「跟随系统」：未选择（或选 system）时用 navigator.language 匹配支持列表，
 *   匹配不上回退 zh；系统语言变化不做热跟随（初始解析即可，见 resolveSystemLocale）；
 * - t(key, vars) 支持 {name} 插值；非 zh 词典缺键时回退 zh 母本；
 * - 不引第三方库（不上 react-i18next/i18next）。
 * - 迁移差异（相对 preview）：剔除 preview/mock 专属词条
 *   （mock.previewTag / footer.popupPreview*），footer.notice 与 app.docTitle
 *   改为正式产品文案。
 */
