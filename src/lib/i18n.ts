/** 全部词典：locale → 词条表（zh 为母本，缺键回退 zh） */
const DICTS: Record<UiLocale, Dict> = { zh, en, de, fr, es, it, pt, ru, ko };

/* ==================== 解析与插值 ==================== */

/** {name} 模板插值；缺变量时保留原样，便于发现漏配 */
function fill(template: string, vars?: TmplVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** 从 navigator.language(s) 解析系统语言（zh-CN → zh；都不支持回退 zh） */
function resolveSystemLocale(): UiLocale {
  const candidates =
    typeof navigator !== "undefined" && navigator.languages?.length
      ? navigator.languages
      : [navigator.language];
  for (const raw of candidates) {
    const base = raw.toLowerCase().split(/[-_]/)[0];
    const hit = UI_LOCALES.find((l) => l.code === base);
    if (hit) return hit.code;
  }
  return "zh";
}

/** 读 localStorage 里记住的选择；无记录 → "system"（跟随系统） */
function readStoredChoice(): UiLocaleChoice {
  try {
    const v = window.localStorage.getItem(UI_LOCALE_STORAGE_KEY);
    if (v === "system") return "system";
    const hit = UI_LOCALES.find((l) => l.code === v);
    if (hit) return hit.code;
  } catch {
    /* localStorage 不可用（隐私模式等）：视为未选择 */
  }
  return "system";
}

/** 选择值 → 生效 locale */
export function resolveLocale(choice: UiLocaleChoice): UiLocale {
  return choice === "system" ? resolveSystemLocale() : choice;
}

/* ==================== 非 React 入口（mock 层用） ==================== */

/** 当前生效 locale 的模块级镜像：引擎等非组件代码取词条用 */
let activeLocale: UiLocale = "zh";

/** mock 层等非 React 环境取当前界面语言 */
export function getUiLocale(): UiLocale {
  return activeLocale;
}

/** 非 React 环境的 t：按当前生效 locale 取词条 */
export function tr(key: DictKey, vars?: TmplVars): string {
  const dict = DICTS[activeLocale] ?? DICTS.zh;
  return fill(dict[key] ?? DICTS.zh[key] ?? key, vars);
}

/* ==================== React 绑定 ==================== */

export type TranslationKey = DictKey;

interface LocaleContextValue {
  /** 用户选择（"system" = 跟随系统），驱动 Select 受控值 */
  choice: UiLocaleChoice;
  /** 当前生效 locale（system 已解析） */
  locale: UiLocale;
  /** 修改选择并写入 localStorage */
  setChoice: (c: UiLocaleChoice) => void;
  t: (key: DictKey, vars?: TmplVars) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

/** 界面语言 Provider — 在 main.tsx 挂在最外层 */
export function LocaleProvider({ children }: { children: ReactNode }) {
  const [choice, setChoiceState] = useState<UiLocaleChoice>(readStoredChoice);
  const locale = useMemo<UiLocale>(() => resolveLocale(choice), [choice]);

  const setChoice = (c: UiLocaleChoice) => {
    try {
      // 记住用户选择；"system" 也落库，重启后仍跟随系统
      window.localStorage.setItem(UI_LOCALE_STORAGE_KEY, c);
    } catch {
      /* 写入失败（隐私模式等）仅本次会话生效 */
    }
    setChoiceState(c);
  };

  const t = useMemo(() => {
    const dict = DICTS[locale];
    return (key: DictKey, vars?: TmplVars): string =>
      fill(dict[key] ?? DICTS.zh[key] ?? key, vars);
  }, [locale]);

  // 同步 <html lang> / 窗口标题 / mock 层镜像；切换即时生效
  useEffect(() => {
    activeLocale = locale;
    document.documentElement.lang = UI_LOCALE_TAGS[locale];
    document.title = DICTS[locale]["app.docTitle"] ?? DICTS.zh["app.docTitle"];
  }, [locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({ choice, locale, setChoice, t }),
    [choice, locale, t],
  );
  // 文件是 .ts（约定路径 i18n.ts），用 createElement 代替 JSX 语法
  return createElement(LocaleContext.Provider, { value }, children);
}

/** 界面语言主 hook：{ locale, choice, setChoice, t } */
export function useAppLocale(): LocaleContextValue {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error("useAppLocale 必须在 LocaleProvider 内使用");
  return ctx;
}
